using System.Diagnostics;

public class Solution
{
    private static readonly (int, int)[] Directions = [(1, 0), (-1, 0), (0, 1), (0, -1)];

    public int ShortestBridge(int[][] grid)
    {
        int n = grid.Length;
        Queue<(int, int)> q = [];   // bfs to find all lands of 1st island
        for (int i = 0; i < n; i++)
        {
            for (int j = 0; j < n; j++)
            {
                if (grid[i][j] == 0)
                {
                    continue;
                }
                q.Enqueue((i, j));  // first land of 1st island
                break;
            }
            if (q.Count > 0)
            {
                break;
            }
        }

        HashSet<(int, int)> island = [(q.Peek())];
        while (q.Count > 0)
        {
            (int i, int j) = q.Dequeue();
            foreach ((int ni, int nj) in NeighborsWithValue(grid, i, j, 1))
            {
                if (island.Contains((ni, nj)))
                {
                    continue;
                }
                q.Enqueue((ni, nj));
                island.Add((ni, nj));
            }
        }

        Queue<(int, (int, int))> q2 = [];   // bfs to find the bridge, steps to reach (i, j)
        HashSet<(int, int)> visited = [];   // visited water cells
        foreach ((int i, int j) in island)
        {
            foreach ((int ni, int nj) in NeighborsWithValue(grid, i, j, 0))
            {
                if (visited.Contains((ni, nj)))
                {
                    continue;
                }
                q2.Enqueue((1, (ni, nj)));
                visited.Add((ni, nj));
            }
        }

        while (q2.Count > 0)
        {
            (int step, (int i, int j)) = q2.Dequeue();
            foreach ((int ni, int nj) in NeighborsWithValue(grid, i, j, 1))
            {
                if (island.Contains((ni, nj)))
                {
                    continue;
                }
                return step;
            }
            foreach ((int ni, int nj) in NeighborsWithValue(grid, i, j, 0))
            {
                if (visited.Contains((ni, nj)))
                {
                    continue;
                }
                q2.Enqueue((step + 1, (ni, nj)));
                visited.Add((ni, nj));
            }
        }
        return 0;
    }

    private static List<(int, int)> NeighborsWithValue(int[][] grid, int i, int j, int target)
    {
        List<(int, int)> res = [];
        int n = grid.Length;
        foreach ((int di, int dj) in Directions)
        {
            int ni = i + di, nj = j + dj;
            if (ni < 0 || ni >= n || nj < 0 || nj >= n || grid[ni][nj] != target)
            {
                continue;
            }
            res.Add((ni, nj));
        }
        return res;
    }
}

